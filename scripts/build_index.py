#!/usr/bin/env python3
"""Generate INDEX.md, skills-index.json and llms.txt from SKILL.md files.

Usage:
  python3 scripts/build_index.py          # write generated files
  python3 scripts/build_index.py --check  # fail if files are stale or a skill is uncategorized
"""

import argparse
import json
import re
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
SKILL_DIRS = ("skills", "specialized-skills")
OUTPUTS = ("INDEX.md", "skills-index.json", "llms.txt")


def read_skill(path: Path) -> dict:
    lines = path.read_text(encoding="utf-8").splitlines()
    end = lines.index("---", 1)
    description = ""
    for i, line in enumerate(lines[1:end], start=1):
        if line.startswith("description:"):
            value = line.split(":", 1)[1].strip()
            if value == ">":
                parts = []
                for cont in lines[i + 1:end]:
                    if not cont.startswith("  "):
                        break
                    parts.append(cont.strip())
                value = " ".join(parts)
            description = value
            break
    scripts = sorted(
        p.name for p in (path.parent / "scripts").glob("*") if p.is_file()
    ) if (path.parent / "scripts").is_dir() else []
    return {
        "name": path.parent.name,
        "path": path.relative_to(ROOT).as_posix(),
        "description": description,
        "scripts": [f"{path.parent.relative_to(ROOT).as_posix()}/scripts/{s}" for s in scripts],
    }


def load_skills() -> dict:
    skills = {}
    for directory in SKILL_DIRS:
        for md in sorted((ROOT / directory).glob("*/SKILL.md")):
            skills[md.parent.name] = read_skill(md)
    return skills


def load_categories() -> dict:
    return json.loads((ROOT / "docs" / "categories.json").read_text(encoding="utf-8"))


def validate(skills: dict, categories: dict) -> list[str]:
    errors = []
    seen = {}
    for category, info in categories.items():
        for name in info["skills"]:
            if name not in skills:
                errors.append(f"category {category!r} lists unknown skill {name!r}")
            if name in seen:
                errors.append(f"skill {name!r} is in two categories: {seen[name]!r} and {category!r}")
            seen[name] = category
    for name in skills:
        if name not in seen:
            errors.append(f"skill {name!r} has no category in docs/categories.json")
    return errors


def short(description: str, limit: int = 160) -> str:
    first = re.split(r"(?<!e\.g)(?<!i\.e)\.\s+(?=[A-Z])", description)[0].rstrip(".")
    return first if len(first) <= limit else first[: limit - 1].rstrip() + "…"


def render(skills: dict, categories: dict) -> dict:
    index_md = ["# Skill Index", "", "Generated by `scripts/build_index.py`. Do not edit by hand.", "",
                f"{len(skills)} skills in {len(categories)} categories. Open the `SKILL.md` that matches the task.", ""]
    llms = ["# Biomni Superagent Pack", "",
            "> Portable, tool-agnostic Agent Skills (SKILL.md) for biomedical research, bioinformatics, "
            "statistics, scientific writing and reproducible analysis. Start with AGENTS.md.", "",
            "## Entry points", "", "- [AGENTS.md](AGENTS.md): operating rules and skill routing",
            "- [INDEX.md](INDEX.md): human-readable catalog", "- [skills-index.json](skills-index.json): machine-readable catalog", ""]
    data = {"count": len(skills), "categories": []}
    for category, info in categories.items():
        index_md += [f"## {category}", "", info["summary"], "", "| Skill | Use it for | Helper scripts |", "|---|---|---|"]
        llms += [f"## {category}", ""]
        entries = []
        for name in info["skills"]:
            s = skills[name]
            scripts = ", ".join(f"`{Path(p).name}`" for p in s["scripts"]) or "-"
            index_md.append(f"| [{name}]({s['path']}) | {short(s['description'])} | {scripts} |")
            llms.append(f"- [{name}]({s['path']}): {short(s['description'])}")
            entries.append({k: s[k] for k in ("name", "path", "description", "scripts")})
        index_md.append("")
        llms.append("")
        data["categories"].append({"name": category, "summary": info["summary"], "skills": entries})
    return {
        "INDEX.md": "\n".join(index_md).rstrip() + "\n",
        "skills-index.json": json.dumps(data, indent=2, ensure_ascii=False) + "\n",
        "llms.txt": "\n".join(llms).rstrip() + "\n",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify generated files are current")
    args = parser.parse_args()
    skills, categories = load_skills(), load_categories()
    errors = validate(skills, categories)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    outputs = render(skills, categories)
    if args.check:
        stale = [n for n in OUTPUTS if not (ROOT / n).is_file() or (ROOT / n).read_text(encoding="utf-8") != outputs[n]]
        if stale:
            print("stale generated files (run scripts/build_index.py): " + ", ".join(stale), file=sys.stderr)
            return 1
        print(f"Index is current ({len(skills)} skills).")
        return 0
    for name, text in outputs.items():
        (ROOT / name).write_text(text, encoding="utf-8")
    print(f"Wrote {', '.join(OUTPUTS)} for {len(skills)} skills.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
